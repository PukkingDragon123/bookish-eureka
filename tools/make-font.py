PX = 128          # font units per glyph pixel
COLS, ROWS = 5, 7
ASCENT_ROWS = 7   # glyph rows sitting above the baseline
DESCEND = set('gjpqy,;$')   # drawn one row lower so tails fall below baseline
UPM = PX * 9


def glyph_pen(rows, drop=0):
    pen = TTGlyphPen(None)
    for ry, row in enumerate(rows):
        y_top = (ASCENT_ROWS - ry - drop) * PX
        x = 0
        while x < COLS:
            if row[x] != '#':
                x += 1
                continue
            run = x
            while run < COLS and row[run] == '#':
                run += 1
            x0, x1 = x * PX, run * PX
            y0, y1 = y_top - PX, y_top
            pen.moveTo((x0, y0))
            pen.lineTo((x0, y1))
            pen.lineTo((x1, y1))
            pen.lineTo((x1, y0))
            pen.closePath()
            x = run
    return pen.glyph()


def main():
    order = ['.notdef', 'space'] + [f'u{ord(c):04X}' for c in G]
    cmap = {ord(c): f'u{ord(c):04X}' for c in G}
    cmap[32] = 'space'
    cmap[0xA0] = 'space'

    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)

    glyphs = {'.notdef': TTGlyphPen(None).glyph(), 'space': TTGlyphPen(None).glyph()}
    metrics = {'.notdef': (COLS * PX + PX, 0), 'space': (3 * PX, 0)}
    for ch, rows in G.items():
        n = f'u{ord(ch):04X}'
        glyphs[n] = glyph_pen(rows, 1 if ch in DESCEND else 0)
        metrics[n] = (COLS * PX + PX, 0)     # 1px letter spacing built in

    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=(ASCENT_ROWS + 1) * PX, descent=-(PX * 2))
    fb.setupNameTable({
        'familyName': 'RitualPixel', 'styleName': 'Regular',
        'psName': 'RitualPixel-Regular', 'fullName': 'RitualPixel',
        'version': 'Version 1.0', 'uniqueFontIdentifier': 'RitualPixel-1.0',
    })
    fb.setupOS2(sTypoAscender=(ASCENT_ROWS + 1) * PX, sTypoDescender=-(PX * 2),
                usWinAscent=(ASCENT_ROWS + 1) * PX, usWinDescent=PX * 2)
    fb.setupPost(isFixedPitch=1)

    buf = io.BytesIO()
    fb.save(buf)
    raw = buf.getvalue()
    b64 = base64.b64encode(raw).decode()

    css = (
        "/* RitualPixel — generated by tools/make-font.py, do not hand-edit */\n"
        "@font-face{font-family:'RitualPixel';font-style:normal;font-weight:400;"
        "font-display:block;src:url(data:font/ttf;base64," + b64 + ") format('truetype');}\n"
    )
    out = os.path.join(ROOT, 'css', 'font.css')
    open(out, 'w').write(css)
    print(f'{len(G)} glyphs, ttf {len(raw)/1024:.1f}KB -> {out}')


if __name__ == '__main__':
    main()
